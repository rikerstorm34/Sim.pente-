// Builds the puzzle bank from the 1983 World Championship games.
//
//   node tools/build-puzzle-bank.mjs [shard] [shards]     (e.g. 0 2 and 1 2 in parallel)
//   node tools/build-puzzle-bank.mjs --merge               (joins shard files into js/puzzle-bank.js)
//
// Every position of every game is examined from the side to move. A puzzle is kept only if its
// goal has exactly one correct move (so the answer is clear-cut), checked with the same goal
// checker the app uses. Themes:
//   chain      a chain of fours that wins (VCF)
//   capwin     the fifth capture wins the game
//   keystone   a capture that also makes a four (takes away a blocker)
//   pair       win a pair safely (the only safe capture among several)
//   fork       one stone threatens two pairs at once, safely
//   defend     stop the opponent's forced win
//   counter    block their open three with a four of your own
//   block      block their open three without leaving a pair to capture
//   save       save a threatened pair without allowing a forced win
// A puzzle may have up to two correct moves; any move that meets the goal is accepted.
// Positions are stored as (game, ply); the app rebuilds them by replaying the game.
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { PLAYABLE_1983, masterEntry } from '../js/master-games.js';
import { setupPosition, checkMove, SEARCH } from '../js/lesson-engine.js';
import {
  applyMove, cloneState, coordName, nearbyMoves, isLegal, winningPointsFor, captureChancesFor, fivePointsFor, openFourPointsFor, other, AXES, inBounds, idx,
} from '../js/rules.js';
import { findVCF } from '../js/ai.js';

SEARCH.forcedWinMs = 2500;
const OUT = (k) => new URL(`../tools/.bank-${k}.json`, import.meta.url);

function vcfFirst(s, who, ms = 400) {
  const t = cloneState(s); t.toMove = who;
  const m = findVCF(t, who, 10, Date.now() + ms, 30000);
  return m ? [m.x, m.y] : null;
}

// Length of the chain (number of attacker moves) by replaying the search greedily.
function chainLength(s, who) {
  const t = cloneState(s);
  for (let k = 1; k <= 12; k++) {
    if (winningPointsFor(t, who).length) return k;
    const m = vcfFirst(t, who, 600);
    if (!m) return 99;
    applyMove(t, ...m);
    if (t.winner === who) return k;
    const f = fivePointsFor(t, who);
    if (!f.length) return 99;
    applyMove(t, ...f[0]);
    if (t.winner !== null) return 99;
  }
  return 99;
}

function solutionsAmong(s, cands, goal, stopAt = 3) {
  const out = [];
  const seen = new Set();
  for (const [x, y] of cands) {
    const k = x + ',' + y;
    if (seen.has(k) || !isLegal(s, x, y)) continue;
    seen.add(k);
    if (checkMove(s, x, y, goal).ok) { out.push(coordName(x, y)); if (out.length >= stopAt) break; }
  }
  return out;
}

// Points on the four lines through (x, y), within 5.
function linePoints(x, y) {
  const out = [];
  for (const [dx, dy] of AXES) for (let k = -5; k <= 5; k++) {
    const nx = x + dx * k, ny = y + dy * k;
    if (inBounds(nx, ny)) out.push([nx, ny]);
  }
  return out;
}

const shard = Number(process.argv[2] || 0), shards = Number(process.argv[3] || 1);
const only = process.env.ONLY ? process.env.ONLY.split(',').map(Number) : null;

if (process.argv[2] === '--merge') {
  const all = [];
  for (let k = 0; k < 8; k++) if (existsSync(OUT(k))) all.push(...JSON.parse(readFileSync(OUT(k), 'utf8')));
  all.sort((a, b) => a.g - b.g || a.ply - b.ply);
  const lines = all.map((p) => '  ' + JSON.stringify(p));
  writeFileSync(new URL('../js/puzzle-bank.js', import.meta.url),
    `// Generated by tools/build-puzzle-bank.mjs from the 1983 World Championship games — do not edit by hand.\n` +
    `// Each puzzle: g = game number, ply = moves played before the puzzle, theme, level (1–5),\n` +
    `// goal (as in lesson-engine.js), answer (the only move that meets the goal), played = what the player chose.\n` +
    `export const PUZZLE_BANK = [\n${lines.join(',\n')},\n];\n`);
  const by = {};
  for (const p of all) by[p.theme] = (by[p.theme] || 0) + 1;
  console.log(all.length, 'puzzles', JSON.stringify(by));
  process.exit(0);
}

const found = [];
const t0 = Date.now();
for (const g of PLAYABLE_1983.filter((x, i) => (only ? only.includes(x.n) : i % shards === shard))) {
  if (g.uncertain) continue;
  const e = masterEntry(g.n);
  const names = e.moves.map(([x, y]) => coordName(x, y));
  const lastTheme = {};
  for (let ply = 8; ply < names.length; ply++) {
    const s = setupPosition({ moves: names.slice(0, ply) });
    if (s.winner !== null) break;
    const me = s.toMove, opp = other(me);
    const played = names[ply];
    const add = (theme, level, goal, answer, nSol = 1) => {
      // Don't repeat a theme for the same side on consecutive turns (it's one combination).
      if (lastTheme[theme] === ply - 2) { lastTheme[theme] = ply; return; }
      lastTheme[theme] = ply;
      found.push({ id: `${g.n}-${ply}-${theme}`, g: g.n, ply, theme, level, goal, answer, played, ...(nSol > 1 ? { alt: true } : {}) });
    };
    const myWins = winningPointsFor(s, me);
    const oppWins = winningPointsFor(s, opp);
    if (myWins.length) {
      // The fifth capture that wins (more instructive than a plain five).
      const capWins = myWins.filter(([x, y]) => captureChancesFor(s, me).some((c) => c.x === x && c.y === y));
      const sol = solutionsAmong(s, myWins, { kind: 'win' });
      if (capWins.length && sol.length === 1 && s.captured[me] >= 8) add('capwin', 2, { kind: 'win' }, sol[0]);
      continue;
    }
    if (oppWins.length) continue; // forced block: not much of a puzzle

    const pick = (sol) => (sol.includes(played) ? played : sol[0]);
    const near = nearbyMoves(s, 2);

    // Chain of fours.
    const first = vcfFirst(s, me);
    if (first) {
      const goal = { all: [{ kind: 'four' }, { kind: 'forcedWin' }] };
      const sol = solutionsAmong(s, nearbyMoves(s, 3), goal, 3);
      if (sol.length && sol.length <= 2) {
        const len = chainLength(s, me);
        if (len >= 2 && len < 99) add('chain', len <= 2 ? 3 : len <= 4 ? 4 : 5, goal, pick(sol), sol.length);
      }
      continue; // with a win available, other themes would be misleading
    }

    // Defence: the opponent threatens a chain of fours.
    const theirs = vcfFirst(s, opp, 300);
    if (theirs) {
      const goal = { kind: 'stopForced' };
      const cands = linePoints(...theirs).concat(captureChancesFor(s, me).map((c) => [c.x, c.y]));
      const sol = solutionsAmong(s, cands, goal, 3);
      if (sol.length && sol.length <= 2) add('defend', 4, goal, pick(sol), sol.length);
      continue;
    }

    const caps = captureChancesFor(s, me);
    const capPts = caps.map((c) => [c.x, c.y]);
    // Keystone: a capture that also makes a four.
    if (caps.length) {
      const goal = { all: [{ kind: 'capture' }, { kind: 'four' }] };
      const ks = solutionsAmong(s, capPts, goal, 3);
      if (ks.length && ks.length <= 2) { add('keystone', 3, goal, pick(ks), ks.length); continue; }
    }
    // Their open three: block it with a four of your own.
    const oppTria = openFourPointsFor(s, opp).length > 0;
    if (oppTria) {
      const g4 = { all: [{ kind: 'blockTria' }, { kind: 'four' }] };
      const s4 = solutionsAmong(s, near, g4, 3);
      if (s4.length && s4.length <= 2) { add('counter', 3, g4, pick(s4), s4.length); continue; }
    }
    // One stone that threatens two pairs, safely.
    const forkGoal = { all: [{ kind: 'doubleCapThreat' }, { kind: 'safe' }] };
    const fk = solutionsAmong(s, near, forkGoal, 3);
    if (fk.length && fk.length <= 2) { add('fork', 3, forkGoal, pick(fk), fk.length); continue; }
    // Win a pair: the only safe capture among several.
    if (caps.length >= 2) {
      const goal = { all: [{ kind: 'capture' }, { kind: 'safe' }, { kind: 'stopForced' }] };
      const sol = solutionsAmong(s, capPts, goal, 3);
      if (sol.length && sol.length <= 2 && sol.length < caps.length) { add('pair', 2, goal, pick(sol), sol.length); continue; }
    }
    // Block their open three without giving up a pair.
    if (oppTria) {
      const goal = { all: [{ kind: 'blockTria' }, { kind: 'safe' }] };
      const all = solutionsAmong(s, near, { kind: 'blockTria' }, 6);
      const sol = solutionsAmong(s, near, goal, 3);
      if (sol.length && sol.length < all.length) { add('block', 2, goal, pick(sol), sol.length); continue; }
    }
    // Save a threatened pair.
    if (captureChancesFor(s, opp).length) {
      const goal = { all: [{ kind: 'noCaptures' }, { kind: 'stopForced' }] };
      const sol = solutionsAmong(s, near, goal, 3);
      if (sol.length && sol.length <= 2) { add('save', 2, goal, pick(sol), sol.length); continue; }
    }
  }
  process.stderr.write(`game ${g.n}: ${found.length} so far (${((Date.now() - t0) / 1000).toFixed(0)} s)\n`);
}
writeFileSync(OUT(shard), JSON.stringify(found));
console.log(`shard ${shard}: ${found.length} puzzles in ${((Date.now() - t0) / 1000).toFixed(0)} s`);
