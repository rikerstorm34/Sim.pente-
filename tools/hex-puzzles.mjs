// Generates Hex puzzles from bot games (no DOM). Usage:
//   node tools/hex-puzzles.mjs [games=80] [seed=1]  → writes js/hex/puzzle-bank.js
// Each puzzle's answer list is complete for its goal (checked again by tests/hex.test.js):
//   connect      finish your chain (the only cell that does)
//   block        stop the only cell where the opponent connects next move
//   bridge       the opponent pushed into one of your bridges: save it
//   fork         make two separate ways to connect; one stone can't block both
//   unbreakable  make a chain of stones and bridges that can't be cut
import { writeFileSync } from 'node:fs';
import { newGame, play, cellName, GOLD, BLUE, emptyCells, other } from '../js/hex/rules.js';
import { chooseMove, winningCells } from '../js/hex/ai.js';
import { bridgeSaves, solutions, unbreakable } from '../js/hex/engine.js';

const GAMES = Number(process.argv[2] || 80);
let seed = Number(process.argv[3] || 1);
const rng = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };
const out = [];
const seen = new Set();
const LEVEL = { connect: 1, block: 2, bridge: 2, fork: 3, unbreakable: 4 };

for (let g = 0; g < GAMES; g++) {
  const n = [7, 9, 9, 11][g % 4];
  const s = newGame(n, false);
  const lv = { [GOLD]: 2 + Math.floor(rng() * 2), [BLUE]: 2 + Math.floor(rng() * 2) };
  for (let k = 0; k < 2; k++) { const e = emptyCells(s); play(s, e[Math.floor(rng() * e.length)]); }
  while (!s.winner) {
    const me = s.toMove, opp = other(me);
    const key = s.board.join('') + me;
    if (!seen.has(key) && s.history.length >= 4) {
      seen.add(key);
      const win = winningCells(s.board, n, me), threat = winningCells(s.board, n, opp);
      const last = s.history[s.history.length - 1].move;
      let theme = null, accept = null;
      if (win.length === 1) { theme = 'connect'; accept = win; }
      else if (!win.length && threat.length === 1) { theme = 'block'; accept = threat; }
      else if (!win.length && !threat.length) {
        const saves = bridgeSaves(s.board, n, me, last);
        const already = unbreakable(s.board, n, me);
        if (saves.length && saves.length <= 2 && !already) { theme = 'bridge'; accept = saves; }
        else if (!already) {
          const fork = solutions(s, { kind: 'fork' });
          if (fork.length >= 1 && fork.length <= 2) { theme = 'fork'; accept = fork; }
          else if (!fork.length) {
            const ub = solutions(s, { kind: 'unbreakable' });
            if (ub.length >= 1 && ub.length <= 3) { theme = 'unbreakable'; accept = ub; }
          }
        }
      }
      if (theme) {
        const names = accept.map((m) => (typeof m === 'number' ? cellName(m, n) : m));
        const gold = [], blue = [];
        s.board.forEach((v, i) => { if (v === GOLD) gold.push(cellName(i, n)); else if (v === BLUE) blue.push(cellName(i, n)); });
        out.push({ theme, level: LEVEL[theme], setup: { size: n, gold, blue, toMove: me === GOLD ? 'gold' : 'blue', last: cellName(last, n) }, goal: { kind: theme === 'bridge' ? 'saveBridge' : theme }, accept: names });
      }
    }
    play(s, chooseMove(s, lv[s.toMove], rng));
  }
  if (g % 10 === 9) process.stderr.write(`${g + 1} games, ${out.length} puzzles\n`);
}
const by = {};
for (const p of out) (by[p.theme] = by[p.theme] || []).push(p);
const keep = [];
for (const [t, list] of Object.entries(by)) keep.push(...list.slice(0, 150).map((p, i) => ({ id: `hx-${t}-${i + 1}`, ...p })));
writeFileSync(new URL('../js/hex/puzzle-bank.js', import.meta.url),
  `// Generated by tools/hex-puzzles.mjs from bot games. Do not edit by hand.\n// ${keep.length} puzzles; every answer list is complete for its goal, checked by tests/hex.test.js.\nexport const BANK = ${JSON.stringify(keep)};\n`);
console.log(Object.fromEntries(Object.entries(by).map(([k, v]) => [k, v.length])), 'kept', keep.length);
