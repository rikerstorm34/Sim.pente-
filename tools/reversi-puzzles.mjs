// Generates Reversi puzzles from bot games (no DOM). Usage:
//   node tools/reversi-puzzles.mjs [games=120] [seed=1]  → writes js/reversi/puzzle-bank.js
// Each puzzle has one stage with a goal and the full list of correct answers (`accept`),
// so the app never has to search while you solve it. Themes:
//   corner    take the only corner that is also the engine's choice
//   safety    most moves hand over a corner; find one that doesn't (and is sound)
//   mobility  leave the opponent the fewest moves (engine agrees within 2 discs)
//   quiet     add the fewest discs to your frontier (engine agrees within 2 discs)
//   endgame   exact: the only move that gets the best result (8–12 empty squares)
//   parity    exact endgame puzzles whose answer is in an odd region
import { writeFileSync } from 'node:fs';
import { newGame, play, movesFor, cellName, counts, GOLD, BLUE, PASS, emptyRegions, CORNERS } from '../js/reversi/rules.js';
import { chooseMove, scoreMoves } from '../js/reversi/ai.js';
import { checkGoal } from '../js/reversi/engine.js';

const GAMES = Number(process.argv[2] || 120);
let seed = Number(process.argv[3] || 1);
const rng = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };

const spec = (s) => {
  const gold = [], blue = [];
  s.board.forEach((v, i) => { if (v === GOLD) gold.push(cellName(i)); else if (v === BLUE) blue.push(cellName(i)); });
  return { gold, blue, toMove: s.toMove === GOLD ? 'gold' : 'blue' };
};
const out = [];
const seen = new Set();
const add = (s, theme, level, goal, accept, extra = {}) => {
  const key = theme + ':' + s.board.join('') + s.toMove;
  if (seen.has(key)) return;
  seen.add(key);
  out.push({ theme, level, goal, accept, setup: spec(s), ...extra });
};

for (let g = 0; g < GAMES; g++) {
  const s = newGame();
  const lv = { [GOLD]: 2 + Math.floor(rng() * 3), [BLUE]: 2 + Math.floor(rng() * 3) };
  while (!s.over) {
    const moves = movesFor(s.board, s.toMove);
    if (!moves.length) { play(s, PASS); continue; }
    const e = counts(s.board).empty;
    if (moves.length >= 3) {
      const quick = e > 12 ? scoreMoves(s.board, s.toMove, { timeMs: 200, maxDepth: 4, exactAt: 0, fullEval: true }).scores : null;
      const top = quick ? Math.max(...quick.values()) : 0;
      const near = (c) => quick && quick.get(c) >= top - 2;
      const sol = (goal) => moves.filter((c) => checkGoal(s, c, goal)).map(cellName);
      if (e > 12) {
        const corners = moves.filter((c) => CORNERS.includes(c));
        if (corners.length === 1 && near(corners[0]) && quick.get(corners[0]) === top) add(s, 'corner', 1, { kind: 'corner' }, [cellName(corners[0])]);
        const safe = sol({ kind: 'noCorner' });
        if (safe.length && safe.length <= 2 && moves.length - safe.length >= 2 && safe.every((n) => near(moves.find((c) => cellName(c) === n)))) add(s, 'safety', 2, { kind: 'noCorner' }, safe);
        const few = sol({ kind: 'fewest' });
        if (few.length === 1 && e < 50 && near(moves.find((c) => cellName(c) === few[0]))) add(s, 'mobility', 3, { kind: 'fewest' }, few);
        const quiet = sol({ kind: 'leastFrontier' });
        if (quiet.length === 1 && e < 50 && e > 20 && near(moves.find((c) => cellName(c) === quiet[0]))) add(s, 'quiet', 3, { kind: 'leastFrontier' }, quiet);
      } else if (e >= 8) {
        const { scores, exact } = scoreMoves(s.board, s.toMove, { timeMs: 4000, exactAt: 12 });
        if (exact) {
          const vals = [...scores.entries()].sort((a, b) => b[1] - a[1]);
          const best = vals[0][1];
          const tops = vals.filter(([, v]) => v === best).map(([c]) => cellName(c));
          const second = vals.find(([, v]) => v < best);
          if (tops.length === 1 && second && best - second[1] >= 4) {
            const odd = emptyRegions(s.board).filter((r) => r.length % 2 === 1).flat().map(cellName);
            const theme = odd.includes(tops[0]) && emptyRegions(s.board).length >= 2 ? 'parity' : 'endgame';
            add(s, theme, e <= 10 ? 4 : 5, { kind: 'best' }, tops, { result: best + 0 });
          }
        }
      }
    }
    play(s, chooseMove(s, lv[s.toMove], rng));
  }
  if (g % 10 === 9) process.stderr.write(`${g + 1} games, ${out.length} puzzles\n`);
}

const byTheme = {};
for (const p of out) (byTheme[p.theme] = byTheme[p.theme] || []).push(p);
const keep = [];
for (const [t, list] of Object.entries(byTheme)) keep.push(...list.slice(0, 120).map((p, i) => ({ id: `rv-${t}-${i + 1}`, ...p })));
writeFileSync(new URL('../js/reversi/puzzle-bank.js', import.meta.url),
  `// Generated by tools/reversi-puzzles.mjs from bot games. Do not edit by hand.\n// ${keep.length} puzzles; every answer list is complete and checked by tests/reversi.test.js.\nexport const BANK = ${JSON.stringify(keep)};\n`);
console.log(Object.fromEntries(Object.entries(byTheme).map(([k, v]) => [k, v.length])), 'kept', keep.length);
